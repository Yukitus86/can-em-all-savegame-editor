using System.ComponentModel;
using System.Globalization;

namespace CanEmAllEditor.Core;

public enum UiLanguage { German, English }

/// <summary>
/// UI texts in German and English. XAML binds through the indexer ({l:T Key}),
/// so switching the language updates the window live.
/// </summary>
public sealed class Loc : INotifyPropertyChanged
{
    public static Loc Instance { get; } = new();

    public event PropertyChangedEventHandler? PropertyChanged;

    public UiLanguage Language { get; private set; } = UiLanguage.English;

    public CultureInfo Culture => CultureInfo.GetCultureInfo(Language == UiLanguage.German ? "de-DE" : "en-US");

    public string this[string key] => Texts.TryGetValue(key, out var t) ? (Language == UiLanguage.German ? t.De : t.En) : key;

    public void SetLanguage(UiLanguage language)
    {
        if (language == Language) return;
        Language = language;
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs("Item[]"));
        PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(nameof(Language)));
    }

    public static string T(string key, params object[] args) =>
        args.Length == 0 ? Instance[key] : string.Format(Instance.Culture, Instance[key], args);

    public static string Num(long value) => value.ToString("N0", Instance.Culture);

    /// <summary>Short money format: 1.5K, 25M, 1.2B.</summary>
    public static string Short(long v)
    {
        var c = Instance.Culture;
        if (v >= 1_000_000_000) return (v / 1e9).ToString("0.##", c) + (Instance.Language == UiLanguage.German ? " Mrd" : "B");
        if (v >= 1_000_000) return (v / 1e6).ToString("0.##", c) + (Instance.Language == UiLanguage.German ? " Mio" : "M");
        if (v >= 10_000) return (v / 1e3).ToString("0.#", c) + "K";
        return v.ToString("N0", c);
    }

